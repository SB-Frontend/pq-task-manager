import type { ReactNode, SVGProps } from "react";

/**
 * Small inline icon set. Hand-drawn on a 24x24 stroke grid so the application
 * needs no icon package - only a handful of glyphs are ever used.
 */
function Icon({ children, ...props }: SVGProps<SVGSVGElement> & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

